CREATE TABLE import_operations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner       VARCHAR(255) NOT NULL,
    started_at  TIMESTAMP NOT NULL,
    status      VARCHAR(16) NOT NULL CHECK (status IN ('RUNNING', 'SUCCESS', 'FAILED')),
    added_count INTEGER,
    error       VARCHAR(1000),
    CHECK ((status = 'SUCCESS' AND added_count IS NOT NULL AND added_count > 0)
        OR (status <> 'SUCCESS' AND added_count IS NULL))
);

CREATE INDEX import_operations_owner_idx ON import_operations (owner, id DESC);
